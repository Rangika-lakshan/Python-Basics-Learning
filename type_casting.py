#--python casting examples--

#float to integer--
price = 10.50
integer_price = int(price)
print(f"{price} --> casted = {integer_price}")

#integer to float--
count = 5
float_count = float(count)
print(f"{count}--> casted ={float_count}")

#number to complex--
x = 100
complex_x = complex(x)
print(f"{x} --> casted = {complex_x}")
